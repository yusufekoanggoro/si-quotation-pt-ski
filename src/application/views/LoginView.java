    private void buttonLoginMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_buttonLoginMouseClicked
        // TODO add your handling code here:
        String username = usernameTextField.getText();
        passwordField.setEchoChar('*');
        String password = String.valueOf(passwordField.getPassword());
  
        //kondisi jika username kosong
        if (username.isEmpty() ) {
            JOptionPane.showMessageDialog(null,"Username tidak boleh kosong");
            usernameTextField.requestFocus();
        } else if(password.isEmpty() || password.equals("password")) {
            JOptionPane.showMessageDialog(null,"Password tidak boleh kosong");
        } else {
            
            EmployeeModel employee = new EmployeeModel();
            employee.setUsername(username);
        
            EmployeeModel findOneEmployeeByUsername = employeeDao.findOneByUsername(employee);
            if(findOneEmployeeByUsername == null) {
                JOptionPane.showMessageDialog(null, "Username atau Password Anda Salah");   
            }else{
                Session.setLevel(findOneEmployeeByUsername.getRoleId());
                String userPasswordInput = Password.getSecurePassword(password);
                String passwordDb = employee.getPassword();
                usernameTextField.setText("");
                passwordField.setText("");
                JOptionPane.showMessageDialog(null, "Berhasil Masuk"); 
                //menutup gui login
                this.dispose();
                //menampilkan gui Menu
                new MenuView().start(); 
            }
        }
    }//GEN-LAST:event_buttonLoginMouseClicked

    private void passwordFieldFocusGained(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_passwordFieldFocusGained
        // TODO add your handling code here:
        String password = String.valueOf(passwordField.getPassword());
        
        if(showPasswordCheckBox.isSelected()){
            passwordField.setEchoChar((char)0);
        }else{
            passwordField.setEchoChar('*');
        }
        
        if(password.toLowerCase().equals("password")){
            passwordField.setText("");
            passwordField.setForeground(Color.black);
        }
    }//GEN-LAST:event_passwordFieldFocusGained

    private void passwordFieldFocusLost(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_passwordFieldFocusLost
        // TODO add your handling code here:
        String password = String.valueOf(passwordField.getPassword());
        if(password.isEmpty()){
            passwordField.setText("password");
            passwordField.setForeground(Color.black);
        }
        if(showPasswordCheckBox.isSelected()){
            passwordField.setEchoChar((char)0);
        }else{
            passwordField.setEchoChar('*');
        }
    }//GEN-LAST:event_passwordFieldFocusLost

    private void showPasswordCheckBoxMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_showPasswordCheckBoxMouseClicked
        // TODO add your handling code here:
        if(showPasswordCheckBox.isSelected()){
            passwordField.setEchoChar((char)0);
        }else{
            passwordField.setEchoChar('*');
        }
    }//GEN-LAST:event_showPasswordCheckBoxMouseClicked

